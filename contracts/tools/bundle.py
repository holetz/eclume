"""Generate the single-file bundle of the v1 contract.

The contract source has three parts: `contracts/openapi-v1.yaml`, `contracts/transcript.schema.json`
and `contracts/fixtures/`. The OpenAPI references the transcript schema through an external `$ref`
and the examples through `externalValue`, so that each fixture exists only once. Tools such as Prism
and type generators do not follow `externalValue`, so this script generates
`contracts/openapi-v1.bundled.yaml`: a document with no external references, with the schema's
`$defs` lifted into `components/schemas` and each fixture inlined as `value`.

Usage:
    uv run python contracts/tools/bundle.py          # rewrites the bundle
    uv run python contracts/tools/bundle.py --check  # exits with 1 if the bundle is stale
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
from pathlib import Path
from typing import Any

import yaml

CONTRACTS = Path(__file__).resolve().parent.parent
SOURCE = CONTRACTS / "openapi-v1.yaml"
SCHEMA_FILE = "./transcript.schema.json"
BUNDLE = CONTRACTS / "openapi-v1.bundled.yaml"
TRANSCRIPT_SCHEMA_NAME = "Transcript"
HEADER = (
    "# GENERATED by contracts/tools/bundle.py from contracts/openapi-v1.yaml,\n"
    "# contracts/transcript.schema.json and contracts/fixtures/. Do not edit by hand.\n"
)


def _rewrite_ref(ref: str) -> str:
    """Translate a source `$ref` into the equivalent pointer inside the bundle."""
    if ref == SCHEMA_FILE:
        return f"#/components/schemas/{TRANSCRIPT_SCHEMA_NAME}"
    for prefix in (f"{SCHEMA_FILE}#/$defs/", "#/$defs/"):
        if ref.startswith(prefix):
            return "#/components/schemas/" + ref.removeprefix(prefix)
    if ref.startswith("#/components/"):
        return ref
    msg = f"$ref with no translation for the bundle: {ref}"
    raise ValueError(msg)


def _load_fixture(relative: str) -> Any:  # noqa: ANN401 — a fixture is JSON or text
    path = (CONTRACTS / relative).resolve()
    if not path.is_relative_to(CONTRACTS / "fixtures"):
        msg = f"externalValue outside contracts/fixtures: {relative}"
        raise ValueError(msg)
    text = path.read_text(encoding="utf-8")
    return json.loads(text) if path.suffix == ".json" else text


def _resolve(node: Any) -> Any:  # noqa: ANN401 — walks arbitrary YAML/JSON
    """Rewrite refs and inline `externalValue`, returning a copy of the node."""
    if isinstance(node, list):
        return [_resolve(item) for item in node]
    if not isinstance(node, dict):
        return node
    result: dict[str, Any] = {}
    for key, value in node.items():
        if key == "$ref" and isinstance(value, str):
            result[key] = _rewrite_ref(value)
        elif key == "externalValue" and isinstance(value, str):
            result["value"] = _load_fixture(value)
        else:
            result[key] = _resolve(value)
    return result


def build() -> str:
    """Build the bundle and return the YAML text."""
    spec = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    transcript = json.loads((CONTRACTS / SCHEMA_FILE).read_text(encoding="utf-8"))

    schemas = spec["components"]["schemas"]
    lifted = {TRANSCRIPT_SCHEMA_NAME: copy.deepcopy(transcript)}
    lifted.update(lifted[TRANSCRIPT_SCHEMA_NAME].pop("$defs"))
    lifted[TRANSCRIPT_SCHEMA_NAME].pop("$schema", None)
    collisions = sorted(set(lifted) & set(schemas))
    if collisions:
        msg = f"transcript schema names collide with components/schemas: {collisions}"
        raise ValueError(msg)
    schemas.update(lifted)

    bundled = _resolve(spec)
    body = yaml.safe_dump(bundled, allow_unicode=True, sort_keys=False, width=100)
    return HEADER + body


def main() -> int:
    """Write the bundle, or only check that it is up to date with `--check`."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed bundle is stale")
    args = parser.parse_args()

    text = build()
    if args.check:
        current = BUNDLE.read_text(encoding="utf-8") if BUNDLE.exists() else ""
        if current != text:
            sys.stderr.write(f"{BUNDLE.relative_to(CONTRACTS.parent)} is stale: run contracts/tools/bundle.py\n")
            return 1
        sys.stdout.write("bundle up to date\n")
        return 0
    BUNDLE.write_text(text, encoding="utf-8")
    sys.stdout.write(f"wrote {BUNDLE.relative_to(CONTRACTS.parent)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
