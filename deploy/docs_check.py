# ruff: noqa: INP001  # loose script, called by the `docs` pillar and by the test; deploy/ is not a package
"""eclume documentation check, stdlib only.

Sweeps `docs/**/*.md`, the root `.md` files and the pillars' `README.md`/`INSTALACAO.md` and flags:

- a relative link to a file that does not exist, or with an `#anchor` to a heading missing in the
  target (GitHub-style slug: lowercase, accents kept, punctuation dropped, a space becomes a hyphen);
- a backticked path that starts with a top-level folder of the repository (without a wildcard, `<`,
  `{` or `$`) and does not exist (a trailing `:line` is ignored);
- a glossary entry out of alphabetical order (ignoring case and accents).

External links (`http:`, `https:`, `mailto:`) are not followed. The exceptions live in `EXCEPTIONS`,
each with its reason; an exception that is no longer needed also fails.

Usage: python3 deploy/docs_check.py [--root .]   (exits 1 and lists the problems, if any)
Contract: docs/standards/code/monorepo.md.
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from itertools import pairwise
from pathlib import Path
from typing import NamedTuple


class PathException(NamedTuple):
    """A backticked path that does not exist in the repository, on purpose."""

    file: str
    path: str
    reason: str


_GENERATED_ENV = "secrets generated by deploy.sh --generate-env; outside git"
_COPIED_ENV = "created by the person from .env.example; outside git"
_HYPOTHETICAL = "hypothetical example of a per-folder AGENTS.md"

EXCEPTIONS: tuple[PathException, ...] = (
    PathException("docs/project/deploy-producao.md", "deploy/.deploy.lock.d", "lock created by a running deploy.sh"),
    PathException(
        "docs/standards/code/monorepo.md", "mobile/.cargo/config.toml", "example of what does not exist, on purpose"
    ),
    PathException("deploy/README.md", "deploy/.env", _COPIED_ENV),
    PathException("deploy/README.md", "deploy/.env.prod", _GENERATED_ENV),
    PathException("docs/project/deploy-producao.md", "deploy/.env.prod", _GENERATED_ENV),
    PathException("docs/how-to/auto-hospedar.md", "deploy/.env.prod", _GENERATED_ENV),
    PathException("docs/how-to/desenvolver-sem-gpu.md", "deploy/.env", _COPIED_ENV),
    PathException(
        "docs/project/deploy-producao.md", "web/test-results/prod", "output of the Playwright production proof"
    ),
    PathException("docs/standards/agents/communication.md", "docs/standards/AGENTS.md", _HYPOTHETICAL),
    PathException("docs/standards/agents/communication.md", "web/AGENTS.md", _HYPOTHETICAL),
    PathException("docs/standards/agents/communication.md", "deploy/AGENTS.md", _HYPOTHETICAL),
)

LINK = re.compile(r"(?<!!)\[(?:[^\]\[]|\[[^\]]*\])*\]\((?P<target>[^)\s]+)(?:\s+\"[^\"]*\")?\)")
BACKTICK = re.compile(r"`(?P<text>[^`\n]+)`")
HEADING = re.compile(r"^(?P<level>#{1,6})\s+(?P<text>.+?)\s*#*\s*$")
FENCE = re.compile(r"^\s*(```|~~~)")
TRAILING_LINE = re.compile(r":\d+(?:-\d+)?$")
EXTERNAL = ("http:", "https:", "mailto:", "tel:")


def slug(heading: str) -> str:
    """The id GitHub gives a Markdown heading."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading)  # link: the text stays
    text = text.replace("`", "").strip().lower()
    text = "".join(c for c in text if c.isalnum() or c in "-_ ")
    return text.replace(" ", "-")


def lines_outside_code(text: str) -> list[tuple[int, str]]:
    """(number, line) of the lines outside fenced code blocks."""
    out, inside = [], False
    for n, line in enumerate(text.splitlines(), 1):
        if FENCE.match(line):
            inside = not inside
            continue
        if not inside:
            out.append((n, line))
    return out


def anchors(text: str) -> set[str]:
    """The slugs of the document's headings, with the `-1`, `-2` suffix of repeated ones."""
    seen: dict[str, int] = {}
    out = set()
    for _, line in lines_outside_code(text):
        if m := HEADING.match(line):
            base = slug(m["text"])
            n = seen.get(base, 0)
            out.add(base if n == 0 else f"{base}-{n}")
            seen[base] = n + 1
    return out


def without_backticks(line: str) -> str:
    """The line without its backticked spans (links inside code do not count)."""
    return BACKTICK.sub("", line)


def link_problems(file: Path, root: Path, cache: dict[Path, set[str]]) -> list[str]:
    """Relative links to a file or anchor that does not exist."""
    text = file.read_text(encoding="utf-8")
    rel = file.relative_to(root).as_posix()
    problems = []
    for n, line in lines_outside_code(text):
        for m in LINK.finditer(without_backticks(line)):
            target = m["target"].strip("<>")
            if target.startswith(EXTERNAL):
                continue
            path, _, anchor = target.partition("#")
            if path.startswith("/"):  # absolute: from the repository root
                dest = (root / path.lstrip("/")).resolve()
            else:
                dest = (file.parent / path).resolve() if path else file
            if path and not dest.exists():
                problems.append(f"{rel}:{n}: link to {path}, which does not exist")
                continue
            if anchor and dest.suffix == ".md" and dest.is_file():
                if dest not in cache:
                    cache[dest] = anchors(dest.read_text(encoding="utf-8"))
                if anchor not in cache[dest]:
                    problems.append(
                        f"{rel}:{n}: anchor #{anchor} does not exist in {dest.relative_to(root).as_posix()}"
                    )
    return problems


def backticked_paths(text: str, top_folders: set[str]) -> list[tuple[int, str]]:
    """(line, path) of the backticked spans that look like a repository path."""
    out = []
    for n, line in lines_outside_code(text):
        for m in BACKTICK.finditer(line):
            path = m["text"].strip()
            # A wildcard, placeholder, variable, command or npm-generated folder is not a committed path.
            if any(c in path for c in "*<>{}$ ") or "/" not in path or "node_modules" in path:
                continue
            path = TRAILING_LINE.sub("", path).rstrip("/")
            if path.split("/", 1)[0] in top_folders:
                out.append((n, path))
    return out


def path_problems(file: Path, root: Path, top_folders: set[str], used: set[PathException]) -> list[str]:
    """Backticked paths that do not exist, outside the exceptions (the used ones go into `used`)."""
    rel = file.relative_to(root).as_posix()
    problems = []
    for n, path in backticked_paths(file.read_text(encoding="utf-8"), top_folders):
        if (root / path).exists():
            continue
        exception = next((e for e in EXCEPTIONS if e.file == rel and e.path == path), None)
        if exception:
            used.add(exception)
        else:
            problems.append(f"{rel}:{n}: path `{path}` does not exist")
    return problems


def sort_key(term: str) -> str:
    """The glossary sort key: without case and without accents."""
    stripped = unicodedata.normalize("NFKD", term)
    return "".join(c for c in stripped if not unicodedata.combining(c)).casefold()


def glossary_terms(text: str) -> list[tuple[int, str]]:
    """(line, term) of each `- [term](…)` or `- **term**` entry of the terms section."""
    out, in_section = [], False
    for n, line in lines_outside_code(text):
        if line.startswith("## "):
            in_section = line.strip() == "## Terms"
            continue
        if in_section and (m := re.match(r"^- (?:\[(?P<link>[^\]]+)\]|\*\*(?P<bold>[^*]+)\*\*)", line)):
            out.append((n, m["link"] or m["bold"]))
    return out


def glossary_problems(text: str) -> list[str]:
    """Entries out of alphabetical order."""
    terms = glossary_terms(text)
    return [
        f"docs/glossary.md:{n}: '{term}' out of alphabetical order (after '{previous}')"
        for (_, previous), (n, term) in pairwise(terms)
        if sort_key(term) < sort_key(previous)
    ]


def files(root: Path) -> list[Path]:
    """The Markdown files checked."""
    found = {
        *root.glob("docs/**/*.md"),
        *root.glob("*.md"),
        *root.glob("*/README.md"),
        *root.glob("*/INSTALACAO.md"),
    }
    # design-system/ is the Claude Design export, versioned as it came (in English, with the paths of
    # the design project); it is not repository documentation. On Windows, `*/README.md` would match
    # its `readme.md`.
    skip = {"node_modules", "design-system"}
    return sorted(p for p in found if not skip.intersection(p.relative_to(root).parts))


def check(root: Path) -> list[str]:
    """Every documentation problem at `root`."""
    top_folders = {p.name for p in root.iterdir() if p.is_dir() and p.name not in {".git", "node_modules"}}
    cache: dict[Path, set[str]] = {}
    used: set[PathException] = set()
    problems: list[str] = []
    for file in files(root):
        problems += link_problems(file, root, cache)
        problems += path_problems(file, root, top_folders, used)
    glossary = root / "docs/glossary.md"
    if glossary.exists():
        problems += glossary_problems(glossary.read_text(encoding="utf-8"))
    problems += [
        f"stale exception: `{e.path}` in {e.file} ({e.reason}); remove it from EXCEPTIONS"
        for e in EXCEPTIONS
        if e not in used
    ]
    return problems


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    problems = check(args.root.resolve())
    sys.stdout.writelines(f"{p}\n" for p in problems)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
